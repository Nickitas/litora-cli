// Пакет cobra связывает команды Lito с доменными моделями и проверяет, что
// параметры CLI действительно участвуют в выполняемом эксперименте. Команда
// dimension анализирует наблюдаемую геометрию без синтетического преобразования.
// Загрузчики входных данных проверяют паспорт батиметрии, его SHA-256 и явно
// предупреждают об alpha- и inferred-профилях литологии. Пустые запуски
// erosion и all используют валидный локальный кэш открытого стартового
// набора Сочи, явно маркируют такой расчёт как demo, а --refresh обновляет
// кэш только после проверки данных. Успех вычисления не повышает статус
// сценария до исследовательского.
// Команда map строит независимую обзорную карту Чёрного моря и не передаёт её
// упрощённый региональный контур в инженерную CERC-модель. Команда mesh
// строит независимые четырёхугольные сетки Gmsh по всей поверхности Чёрного моря и
// ранжирует алгоритмы по сохранению локальных площадей берега и качеству ячеек.
// Подкоманда seabed render читает принятую батиметрическую MSH-модель и её
// паспорта, после чего создаёт обзорную карту глубин без внутренних рёбер и
// три непрореженных фрагмента фактической сетки с локальными изобатами,
// метрический 3D-рельеф и три автоматических профиля до глубоководного ядра.
// Подкоманда seabed build связывает плоский MSH с подтверждённой батиметрией,
// проверяет паспорт и контрольную сумму источника, сохраняет MSH/VTU/CSV/JSON
// и не выдаёт геометрию дна за решение 2D-гидродинамики.
// Подкоманда seabed adapt строит отдельное объяснимое поле размера ADAPT-01 по
// расстоянию до берега, береговой кривизне и градиенту глубины, ограничивает
// рост по соседним рёбрам и сохраняет CSV, JSON и SVG без преждевременного
// запуска генератора Gmsh. Подкоманда seabed generate-adaptive использует это
// поле как Gmsh Background Field, выполняет предзапусковую оценку ресурсов,
// full-quad преобразование и строгую проверку физически размеченной границы.
// Подкоманда seabed compare-adaptive последовательно запускает Delaunay,
// Frontal-Delaunay for Quads и Packing of Parallelograms на общих контрольных
// полях, переносит глубины исходной модели на полученные сетки и сохраняет
// воспроизводимый рейтинг вместе с тайм-аутами, памятью и журналами ошибок.
// Подкоманда seabed expert-set создаёт AI-01: слепые SVG-карточки общих
// фрагментов успешных сеток, лист экспертной оценки и закрытый ключ. Она
// географически разделяет обучение и проверку, но не обучает ИИ и не меняет
// детерминированный рейтинг ADAPT-03.
// Подкоманда seabed assess-ml сопоставляет размеченные карточки с метриками
// ADAPT-03 и рекомендует ridge-кандидат только при измеримом улучшении на
// независимых географических районах; без достаточной разметки она сохраняет
// проверяемый отказ от ML.
// Стандартная справка Cobra локализована, поэтому заголовки и флаг --help не
// возвращают англоязычный текст в русскоязычном приложении.
// Выбор других акваторий отсутствует: береговые и батиметрические загрузчики
// отклоняют координаты вне области Чёрного моря.
