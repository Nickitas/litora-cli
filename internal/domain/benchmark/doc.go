// Package benchmark содержит исследовательские эталонные участки, подбор
// параметров и диагностические метрики модели береговой эрозии.
//
// Результаты подбора не заменяют независимую физическую валидацию: команда
// отделяет пространственную отложенную выборку, учитывает неопределённости,
// срок каждого наблюдения и ограничивает сопоставление с береговой линией, но
// малый объём исходных наблюдений всё равно требует осторожной интерпретации.
// Межсайтовая leave-one-site-out проверка оценивает переносимость параметров
// на полностью исключённый эталон.
//
// Предустановки сценарного анализа являются параметрическими экспериментами:
// множители ветра, подъёма уровня моря и штормового воздействия заданы вручную
// и не должны интерпретироваться как климатические траектории RCP. Конфигурация
// явно хранит ручной способ получения параметров, отсутствие внешнего источника
// и прокси уровня моря, преобразуемый в множитель ветрового воздействия.
// Числовые диапазоны и происхождение валидируются до запуска симуляции.
