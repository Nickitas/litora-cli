// Package seabed связывает геопривязанную 2D-сетку акватории Чёрного моря с
// батиметрией. Пакет назначает узловые отметки без неявного заполнения NoData,
// классифицирует берег, острова и открытые границы, вводит нулевое береговое
// условие и создаёт проверяемый журнал всех коррекций прибрежной маски. Для
// принятых четырёхугольных ячеек пакет рассчитывает площадь, диапазон и среднее
// глубины, уклон, экспозицию, шероховатость и морфометрическую зону. Принятая
// модель экспортируется в самодостаточный Gmsh MSH 2.2 с Z = elevation_m,
// физическими группами границ и проверяемыми NodeData/ElementData; плоские MSH
// распознаются отдельно и не трактуются как батиметрия. Для ParaView пакет
// создаёт VTK XML UnstructuredGrid с теми же полями, а согласованный табличный
// набор включает nodes.csv, cells.csv, profiles.csv и пространственные
// метаданные с проекцией, вертикальной системой и единицами. Паспорт экспорта
// можно строго прочитать повторно перед построением обзорной карты. Для VIEW-03
// пакет воспроизводимо выбирает западный, восточный и северный разрезы от
// внешнего берега к глубоководному ядру по фактическим рёбрам сетки. Отдельный
// пакет adaptive использует эту принятую модель как неизменяемый источник
// расстояния до берега и производных BATHY-03 для поля размера ADAPT-01.
// QA-02 использует общий ModelDepthSampler и отдельную опорную модель для
// расчёта ошибок глубины, объёма, зон, изобат, уклона, способа выборки и
// геометрии сетки. Паспорт опорного источника связывает пороги с его
// горизонтальным разрешением и вертикальной неопределённостью и не позволяет
// выдавать межпродуктовый контроль за независимую публикационную проверку.
