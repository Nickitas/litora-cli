// Package adaptive строит воспроизводимое поле требуемого размера ячейки для
// акватории Чёрного моря. Расчёт использует только проверяемые признаки модели
// дна: расстояние до внешнего берега и островов, локальный поворот береговой
// линии и градиент глубины из BATHY-03. Результат задаётся в узлах принятого
// метрического каркаса LAEA и сглаживается по его рёбрам с явными ограничениями
// отношения соседних размеров и пространственной скорости роста. Для ADAPT-02
// пакет потоково читает этот контракт, сохраняет зональную статистику рёбер и
// машинный отчёт запуска Gmsh; собственно генерация изолирована в пакете mesh.
// Для ADAPT-03 пакет переносит одно и то же поле в контрольные диапазоны,
// сравнивает три генератора по сохранению берега и батиметрии, геометрии ячеек,
// соответствию целевому размеру и вычислительной устойчивости. Рейтинг,
// неуспешные запуски, контрольные суммы входов и все составляющие оценки
// сохраняются в версионированных JSON/TSV без визуальной субъективности.
