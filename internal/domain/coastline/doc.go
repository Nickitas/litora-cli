// Package coastline предоставляет функциональность для загрузки, валидации и анализа данных береговой линии.
//
// Основные возможности:
//   - Загрузка данных из локальных JSON-файлов или удалённых GeoJSON-источников
//   - Кэширование данных для ускорения последующих загрузок
//   - Валидация геометрии с автоматическим исправлением ошибок
//   - Анализ и визуализация береговой линии
//   - Поддержка различных форматов GeoJSON (Point, LineString, Polygon, MultiPolygon)
//
// Основные типы:
//   - LoadOptions: параметры загрузки данных
//   - LoadResult: результат загрузки с валидацией
//   - PolygonLoadResult: внешний контур водоёма и островные отверстия для 2D-сетки
//   - ValidationReport: отчёт о проверке и исправлениях
//   - GeoBounds: прямоугольная область на карте
//
// Пример использования:
//
//	result, err := coastline.Load(coastline.LoadOptions{
//	    LocalPath: "data/black-sea.json",
//	})
//	if err != nil {
//	    log.Fatal(err)
//	}
//	fmt.Printf("Загружено %d точек\n", len(result.Points))
