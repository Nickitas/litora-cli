// Package mesh реализует воспроизводимую подготовку границы Чёрного моря,
// запуск открытого генератора Gmsh и независимую оценку качества плоских
// четырёхугольных сеток. Прямая и обратная сферическая LAEA-проекции связывают
// X/Y каждого узла с WGS 84; географические координаты сохраняются в MSH как
// longitude_deg и latitude_deg. ADAPT-02 передаёт узловое поле размера в Gmsh
// через PostView, оценивает объём до запуска, сохраняет физические метки берега
// при согласованном full-quad делении и проверяет топологию полного MSH.
// Плоский экспорт получает маркеры lito-mesh/v1, поэтому его Z = 0 нельзя принять за измеренную глубину. Пакет не подменяет
// box-counting-сетку и не превращает одномерную модель CERC в двумерную
// гидродинамическую модель. Геометрическая оценка QuadrilateralQuality единообразно
// используется и при ранжировании генераторов, и на картах качества VIEW-02.
